// Una compra nueva siempre señala la cuenta real que pagó; no crea gastos huérfanos.
test('impide guardar una compra sin cuenta y actualiza el saldo tras agregarla', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /probar con datos de ejemplo/i }).click()
  await expect(page.getByRole('heading', { name: /Hola, Danilo/ })).toBeVisible()
  await archiveDemoAssets(page)
  await page.reload()
  await page.getByRole('button', { name: 'Nuevo movimiento', exact: true }).click()
  await expect(page.getByLabel('¿Con qué pagaste?').locator('option')).toHaveCount(2)
  await expect(page.getByLabel('¿Con qué pagaste?').locator('option:checked')).toHaveText('Selecciona una cuenta')
  await page.getByRole('textbox', { name: /^Monto/ }).fill('25.000')
  await page.getByLabel('Categoría', { exact: true }).selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Agregar cuenta' }).click()
  const accountDialog = page.getByRole('dialog', { name: 'Agregar cuenta', exact: true })
  await accountDialog.getByLabel('Nombre', { exact: true }).fill('Mi banco')
  await accountDialog.getByLabel('Saldo inicial').fill('100.000')
  await accountDialog.getByRole('button', { name: 'Crear cuenta' }).click()
  await expect(accountDialog).toBeHidden()
  await page.getByRole('button', { name: 'Añadir detalles' }).click()
  await page.getByLabel('Comercio o nota').fill('Compra cotidiana')
  await page.getByRole('button', { name: 'Guardar movimiento', exact: true }).click()
  await expect(page.getByText('Movimiento guardado', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Actividad', exact: true }).click()
  const purchase = page.locator('.transaction').filter({ hasText: 'Compra cotidiana' })
  await expect(purchase).toHaveCount(1)
  await expect(purchase).toContainText('Mi banco')
  await expect(purchase).toContainText('25.000')
  await page.reload()
  await expect(page.locator('.transaction').filter({ hasText: 'Compra cotidiana' })).toHaveCount(1)
  await page.getByRole('link', { name: 'Cuentas', exact: true }).click()
  await expect(page.locator('.account-row').filter({ hasText: 'Mi banco' })).toContainText('75.000')
  await expect(page.locator('.account-row').filter({ hasText: 'Tarjeta de ejemplo' })).toContainText('185.000')
})

// Archiva solo los activos ficticios de la demo para comprobar el estado de solo deudas.
async function archiveDemoAssets(page) {
  await page.evaluate(async () => {
    const { db } = await import('/src/data/db.js')
    const assets = await db.accounts.filter((account) => account.kind === 'asset').toArray()
    await db.accounts.bulkPut(assets.map((account) => ({ ...account, archived: true })))
  })
}
